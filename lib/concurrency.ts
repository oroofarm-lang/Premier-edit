/**
 * Runs `fn` over `items` with at most `limit` in flight at once. Plain
 * `Promise.all` would fire every request simultaneously — fine for a handful
 * of items, a good way to trip a provider's rate limit for a folder of 38.
 */
export async function mapWithConcurrency<T, R>(
  items: T[],
  limit: number,
  fn: (item: T, index: number) => Promise<R>,
): Promise<R[]> {
  const results: R[] = new Array(items.length);
  let next = 0;

  async function worker() {
    while (next < items.length) {
      const index = next++;
      results[index] = await fn(items[index], index);
    }
  }

  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return results;
}
